-- 2. Second Normal Form (2NF):
--    - Already in 1NF.
--    - Every non-key attribute is fully functionally dependent on the primary key.
--    - In MEMBERSHIP and REGISTRATION, surrogate primary keys are used,
--      and non-key attributes (join_date, status, registration_date) depend 
--      on the whole primary key.
-- 3. Third Normal Form (3NF):
--    - Already in 2NF.
--    - No transitive dependencies exist (non-key attribute -> non-key attribute).
--    - For example, EVENT only stores club_id; club details like club_name 
--      and faculty_coordinator live strictly in the CLUB table.
--    - REGISTRATION references student_id and event_id; student names and
--      event venues are not duplicated in REGISTRATION.
-- --------------------------------------------------------------------

