-- 1. STUDENT Table
-- Stores student information.
-- Year constraint ensures valid college year (1 to 4).
CREATE TABLE STUDENT (
    student_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name    VARCHAR2(100) NOT NULL,
    email           VARCHAR2(100) NOT NULL UNIQUE,
    department      VARCHAR2(50)  NOT NULL,
    year            NUMBER(1)     NOT NULL,
    CONSTRAINT chk_student_year CHECK (year BETWEEN 1 AND 4)
);

-- 2. CLUB Table
-- Stores student clubs on campus.
CREATE TABLE CLUB (
    club_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_name            VARCHAR2(100) NOT NULL UNIQUE,
    category             VARCHAR2(50)  NOT NULL,
    faculty_coordinator  VARCHAR2(100) NOT NULL
);

-- 3. EVENT Table
-- Stores events hosted by clubs.
-- Foreign key relates to CLUB table.
CREATE TABLE EVENT (
    event_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name  VARCHAR2(150) NOT NULL,
    event_date  DATE          NOT NULL,
    venue       VARCHAR2(100) NOT NULL,
    club_id     NUMBER        NOT NULL,
    CONSTRAINT fk_event_club FOREIGN KEY (club_id) 
        REFERENCES CLUB(club_id) ON DELETE CASCADE
);

-- 4. MEMBERSHIP Table
-- Represents a student joining a club.
-- Unique constraint ensures a student cannot join the same club twice.
CREATE TABLE MEMBERSHIP (
    membership_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      NUMBER NOT NULL,
    club_id         NUMBER NOT NULL,
    join_date       DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_membership_student FOREIGN KEY (student_id) 
        REFERENCES STUDENT(student_id) ON DELETE CASCADE,
    CONSTRAINT fk_membership_club FOREIGN KEY (club_id) 
        REFERENCES CLUB(club_id) ON DELETE CASCADE,
    CONSTRAINT uq_student_club UNIQUE (student_id, club_id)
);

-- 5. REGISTRATION Table
-- Records a student registering for an event.
-- Status is restricted to REGISTERED, CANCELLED, or ATTENDED.
-- Unique constraint prevents duplicate registrations for the same event.
CREATE TABLE REGISTRATION (
    registration_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id          NUMBER NOT NULL,
    event_id            NUMBER NOT NULL,
    status              VARCHAR2(20) DEFAULT 'REGISTERED' NOT NULL,
    registration_date   DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_reg_student FOREIGN KEY (student_id) 
        REFERENCES STUDENT(student_id) ON DELETE CASCADE,
    CONSTRAINT fk_reg_event FOREIGN KEY (event_id) 
        REFERENCES EVENT(event_id) ON DELETE CASCADE,
    CONSTRAINT uq_student_event UNIQUE (student_id, event_id),
    CONSTRAINT chk_reg_status CHECK (status IN ('REGISTERED', 'CANCELLED', 'ATTENDED'))
);

COMMIT;
